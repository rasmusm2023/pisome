export function suggestSpanishPlaces(
  query: string,
  limit = 8,
): SpanishPlaceSuggestion[] {
  const q = fold(query.trim());
  if (q.length < 2) return [];

  const scored: {
    name: string;
    province: string;
    weight: number;
    score: number;
  }[] = [];

  for (const row of PLACES) {
    const name = row[0];
    const province = row[1];
    const weight = row[2];
    const aliases = row[3] ?? [];
    let score = 99;
    for (const candidate of [name, ...aliases]) {
      const f = fold(candidate);
      if (f === q) score = Math.min(score, 0);
      else if (f.startsWith(q)) score = Math.min(score, 1);
      else if (f.split(/[\s/-]+/).some((part) => part.startsWith(q))) {
        score = Math.min(score, 2);
      } else if (q.length >= 4 && f.includes(q)) {
        score = Math.min(score, 3);
      }
    }
    if (score === 99) continue;
    scored.push({ name, province, weight, score });
  }

  scored.sort(
    (a, b) =>
      a.score - b.score ||
      b.weight - a.weight ||
      a.name.localeCompare(b.name, "es"),
  );

  const seen = new Set<string>();
  const out: SpanishPlaceSuggestion[] = [];
  for (const place of scored) {
    const key = fold(place.name);
    if (seen.has(key)) continue;
    seen.add(key);
    out.push({
      kind: "city",
      value: place.name,
      city: place.name,
      label: placeLabel(place.name, place.province),
    });
    if (out.length >= limit) break;
  }
  return out;
}
