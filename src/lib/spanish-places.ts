/** Client-safe Spanish place gazetteer for location autocomplete. */

export type SpanishPlaceSuggestion = {
  label: string;
  kind: "city";
  value: string;
  city: string;
};

type PlaceRow =
  | readonly [name: string, province: string, weight: number]
  | readonly [name: string, province: string, weight: number, aliases: readonly string[]];

function fold(value: string) {
  return value
    .normalize("NFD")
    .replace(/[\u0300-\u036f]/g, "")
    .toLowerCase();
}

function placeLabel(name: string, province: string) {
  return province && province !== name ? `${name}, ${province}` : name;
}

